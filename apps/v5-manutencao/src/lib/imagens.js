const FALLBACK_GENERICO = 'https://images.unsplash.com/photo-1581244277943-fe4a9c777189?w=800&q=80'

function hashStr(str) {
  let h = 0
  for (let i = 0; i < str.length; i++) {
    h = ((h << 5) - h + str.charCodeAt(i)) | 0
  }
  return Math.abs(h)
}

export function getImagemServico(servico) {
  if (!servico) return FALLBACK_GENERICO

  // 1. Imagem específica guardada na BD
  if (servico.imagem_url) return servico.imagem_url

  // 2. Pool por categoria/sub_grupo com hash determinístico pelo id ou nome
  const cat = servico.categoria || servico.categoria_id || ''
  const sub = servico.sub_grupo || ''
  if (cat && sub) {
    const key = `${cat}/${sub}`
    const pool = POOL_POR_SUB_GRUPO[key]
    if (pool && pool.length > 0) {
      const seed = servico.id || servico.nome || ''
      return pool[hashStr(seed) % pool.length]
    }
  }

  // 3. Fallback por categoria
  const catKey = cat.replace(/-/g, '_')
  return FALLBACK_POR_CATEGORIA[catKey] || FALLBACK_GENERICO
}
